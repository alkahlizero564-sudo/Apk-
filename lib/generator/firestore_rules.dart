// Firestore security rules for a project whose database is Firebase: the same ownership model as the
// Supabase policies (catalog / customer / shared / admin tables, admin-only fields, notifications).

import '../models/schema.dart';

class FirestoreRulesGenerator {
  FirestoreRulesGenerator(this.prefix, this.schema);

  final String prefix;
  final DbSchema schema;

  String get p => prefix;

  String build() {
    final b = StringBuffer()
      ..writeln("rules_version = '2';")
      ..writeln('// Generated by Alpha for project "$p". Collections: ${p}_<table>.')
      ..writeln('service cloud.firestore {')
      ..writeln('  match /databases/{database}/documents {')
      ..writeln('    function signedIn() { return request.auth != null; }')
      ..writeln('    function uid() { return request.auth.uid; }')
      ..writeln('    function email() { return signedIn() ? request.auth.token.get("email", "").lower() : ""; }')
      ..writeln('    function isAdmin() {')
      ..writeln('      return signedIn() && (exists(/databases/\$(database)/documents/${p}_admins/\$(email()))')
      ..writeln('        || get(/databases/\$(database)/documents/${p}_profiles/\$(uid())).data.get("role", "") == "admin");')
      ..writeln('    }')
      ..writeln('    function owns(data) { return signedIn() && data.get("customer_id", "") == uid(); }')
      ..writeln()
      ..writeln('    match /${p}_admins/{mail} { allow read: if signedIn() && (mail == email() || isAdmin()); allow write: if isAdmin(); }')
      ..writeln('    match /${p}_profiles/{id} {')
      ..writeln('      allow read: if signedIn() && (id == uid() || isAdmin());')
      ..writeln('      allow create: if signedIn() && id == uid() && request.resource.data.get("role", "customer") == "customer";')
      ..writeln('      allow update: if isAdmin() || (signedIn() && id == uid() && !request.resource.data.diff(resource.data).affectedKeys().hasAny(["role"]));')
      ..writeln('    }')
      ..writeln('    match /${p}_device_tokens/{token} {')
      ..writeln('      allow read, delete: if signedIn() && resource.data.user_id == uid();')
      ..writeln('      allow create, update: if signedIn() && request.resource.data.user_id == uid();')
      ..writeln('    }')
      ..writeln('    match /${p}_notifications/{id} {')
      ..writeln('      allow read: if signedIn() && (resource.data.get("to_user", "") == uid() || resource.data.get("created_by", "") == uid()')
      ..writeln('        || resource.data.get("to_role", "") == "customer" || (resource.data.get("to_role", "") == "admin" && isAdmin()));')
      ..writeln('      allow create: if signedIn() && request.resource.data.created_by == uid()')
      ..writeln('        && (request.resource.data.get("to_role", "") == "admin" || request.resource.data.get("to_user", "") == uid() || isAdmin());')
      ..writeln('      allow update: if signedIn() && (resource.data.get("to_user", "") == uid() || isAdmin())')
      ..writeln('        && request.resource.data.diff(resource.data).affectedKeys().hasOnly(["read_at"]);')
      ..writeln('    }');
    for (final t in schema.tables) {
      b.writeln(_table(t));
    }
    b
      ..writeln('  }')
      ..writeln('}');
    return b.toString();
  }

  String _table(DbTable t) {
    final adminCols = t.columns.where((c) => c.adminOnly).map((c) => '"${c.name}"').toList();
    final noAdminFieldsOnCreate = adminCols.isEmpty ? 'true' : '!request.resource.data.keys().hasAny([${adminCols.join(', ')}])';
    final noAdminFieldsOnUpdate = adminCols.isEmpty
        ? 'true'
        : '!request.resource.data.diff(resource.data).affectedKeys().hasAny([${adminCols.join(', ')}])';
    final sameOwner = 'request.resource.data.get("customer_id", "") == resource.data.get("customer_id", "")';
    final lines = switch (t.owner) {
      TableOwner.catalog => [
          'allow read: if signedIn();',
          'allow write: if isAdmin();',
        ],
      TableOwner.customer => [
          'allow read: if isAdmin() || owns(resource.data);',
          'allow create: if isAdmin() || (owns(request.resource.data) && $noAdminFieldsOnCreate);',
          'allow update: if isAdmin() || (owns(resource.data) && $sameOwner && $noAdminFieldsOnUpdate);',
          'allow delete: if isAdmin() || owns(resource.data);',
        ],
      TableOwner.shared => [
          'allow read: if signedIn();',
          'allow create: if isAdmin() || (owns(request.resource.data) && $noAdminFieldsOnCreate);',
          'allow update: if isAdmin() || (owns(resource.data) && $sameOwner && $noAdminFieldsOnUpdate);',
          'allow delete: if isAdmin() || owns(resource.data);',
        ],
      TableOwner.admin => [
          'allow read, write: if isAdmin();',
        ],
    };
    return '    // ${t.label}: ${t.owner.label}\n'
        '    match /${p}_${t.name}/{id} {\n${lines.map((l) => '      $l').join('\n')}\n    }';
  }

  /// Composite indexes the engines' queries need (customer rows ordered by date).
  String indexes() {
    final idx = schema.tables
        .where((t) => t.hasOwnerColumn)
        .map((t) => '    {"collectionGroup": "${p}_${t.name}", "queryScope": "COLLECTION", "fields": ['
            '{"fieldPath": "customer_id", "order": "ASCENDING"}, {"fieldPath": "created_at", "order": "DESCENDING"}]}')
        .join(',\n');
    return '{\n  "indexes": [\n$idx\n  ],\n  "fieldOverrides": []\n}\n';
  }
}
