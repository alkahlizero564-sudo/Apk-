// Turns a project's schema into one PostgreSQL script for Supabase: accounts and roles, every business table
// with its row level security, admin-only columns, notifications between the two apps, realtime and stats.
// The script is idempotent: running it again after editing the schema adds the new tables / columns and
// replaces the policies and triggers, without losing data.

import '../models/schema.dart';

class SqlGenerator {
  SqlGenerator(this.prefix, this.schema, {this.admins = const []});

  final String prefix;
  final DbSchema schema;
  final List<String> admins;

  String get p => prefix;

  static String lit(String v) => "'${v.replaceAll("'", "''")}'";

  String table(DbTable t) => 'public.${p}_${t.name}';

  String build() {
    final b = StringBuffer()
      ..writeln('-- Generated by Alpha for project "$p". Safe to run again.')
      ..writeln('-- Tables: ${schema.tables.map((t) => '${p}_${t.name}').join(', ')}')
      ..writeln()
      ..writeln(baseSql());
    for (final t in schema.tables) {
      b
        ..writeln()
        ..writeln(tableSql(t));
    }
    b
      ..writeln()
      ..writeln(statsSql())
      ..writeln()
      ..writeln(realtimeSql())
      ..writeln()
      ..writeln("notify pgrst, 'reload schema';");
    return b.toString();
  }

  String baseSql() {
    final adminRows = admins
        .map((e) => e.trim().toLowerCase())
        .where((e) => e.contains('@'))
        .map((e) => '(${lit(e)})')
        .join(', ');
    return '''
-- ===== Accounts, roles, devices and notifications =====
create table if not exists public.${p}_admins (email text primary key);
${adminRows.isEmpty ? '' : 'insert into public.${p}_admins (email) values $adminRows on conflict do nothing;'}

create table if not exists public.${p}_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  phone text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.${p}_is_admin() returns boolean
language sql stable security definer set search_path = public as \$\$
  select exists (select 1 from public.${p}_profiles where id = auth.uid() and role = 'admin')
\$\$;

create or replace function public.${p}_role_for(mail text) returns text
language sql stable security definer set search_path = public as \$\$
  select case when exists (select 1 from public.${p}_admins a where lower(a.email) = lower(coalesce(mail, '')))
         then 'admin' else 'customer' end
\$\$;

create or replace function public.${p}_handle_new_user() returns trigger
language plpgsql security definer set search_path = public as \$\$
begin
  insert into public.${p}_profiles (id, email, full_name, phone, role)
  values (new.id, new.email,
          nullif(new.raw_user_meta_data->>'full_name', ''),
          nullif(new.raw_user_meta_data->>'phone', ''),
          public.${p}_role_for(new.email))
  on conflict (id) do nothing;
  return new;
end \$\$;
drop trigger if exists ${p}_on_auth_user_created on auth.users;
create trigger ${p}_on_auth_user_created after insert on auth.users
  for each row execute function public.${p}_handle_new_user();

-- Accounts that already exist (e.g. the owner) get a profile, and listed admins become admins.
insert into public.${p}_profiles (id, email, role)
  select u.id, u.email, public.${p}_role_for(u.email) from auth.users u
  on conflict (id) do update set role = case when excluded.role = 'admin' then 'admin' else public.${p}_profiles.role end;

-- A new admin email makes an existing account admin right away.
create or replace function public.${p}_admin_added() returns trigger
language plpgsql security definer set search_path = public as \$\$
begin
  update public.${p}_profiles set role = 'admin' where lower(email) = lower(new.email);
  return new;
end \$\$;
drop trigger if exists ${p}_admin_added on public.${p}_admins;
create trigger ${p}_admin_added after insert on public.${p}_admins
  for each row execute function public.${p}_admin_added();

-- Nobody can make themselves admin; only an admin changes roles.
create or replace function public.${p}_protect_role() returns trigger
language plpgsql security definer set search_path = public as \$\$
begin
  if new.role is distinct from old.role and auth.uid() is not null and not public.${p}_is_admin() then
    raise exception 'only an admin can change roles';
  end if;
  return new;
end \$\$;
drop trigger if exists ${p}_protect_role on public.${p}_profiles;
create trigger ${p}_protect_role before update on public.${p}_profiles
  for each row execute function public.${p}_protect_role();

alter table public.${p}_profiles enable row level security;
alter table public.${p}_admins enable row level security;
grant select, insert, update, delete on public.${p}_profiles, public.${p}_admins to authenticated;
drop policy if exists "${p} profiles read" on public.${p}_profiles;
create policy "${p} profiles read" on public.${p}_profiles for select to authenticated
  using (id = auth.uid() or public.${p}_is_admin());
drop policy if exists "${p} profiles update" on public.${p}_profiles;
create policy "${p} profiles update" on public.${p}_profiles for update to authenticated
  using (id = auth.uid() or public.${p}_is_admin()) with check (id = auth.uid() or public.${p}_is_admin());
drop policy if exists "${p} admins manage" on public.${p}_admins;
create policy "${p} admins manage" on public.${p}_admins for all to authenticated
  using (public.${p}_is_admin()) with check (public.${p}_is_admin());

-- Shared helper: updated_at follows every change.
create or replace function public.${p}_touch() returns trigger
language plpgsql as \$\$
begin
  new.updated_at := now();
  return new;
end \$\$;

create table if not exists public.${p}_device_tokens (
  token text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  app text not null check (app in ('single', 'customer', 'admin')),
  platform text not null default 'android',
  updated_at timestamptz not null default now()
);
alter table public.${p}_device_tokens enable row level security;
grant select, insert, update, delete on public.${p}_device_tokens to authenticated;
drop policy if exists "${p} own devices" on public.${p}_device_tokens;
create policy "${p} own devices" on public.${p}_device_tokens for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- A phone can move between accounts, so registration goes through this function.
create or replace function public.${p}_register_device(device_token text, app_name text, device_platform text default 'android')
returns void language plpgsql security definer set search_path = public as \$\$
begin
  if auth.uid() is null then raise exception 'sign in first'; end if;
  insert into public.${p}_device_tokens (token, user_id, app, platform, updated_at)
  values (device_token, auth.uid(), app_name, device_platform, now())
  on conflict (token) do update set user_id = auth.uid(), app = excluded.app,
    platform = excluded.platform, updated_at = now();
end \$\$;
grant execute on function public.${p}_register_device(text, text, text) to authenticated;

create table if not exists public.${p}_notifications (
  id bigint generated always as identity primary key,
  to_user uuid references auth.users(id) on delete cascade,
  to_role text check (to_role in ('customer', 'admin')),
  title text not null,
  body text not null default '',
  data jsonb not null default '{}',
  created_by uuid default auth.uid(),
  read_at timestamptz,
  created_at timestamptz not null default now(),
  check (to_user is not null or to_role is not null)
);
alter table public.${p}_notifications enable row level security;
grant select, insert, update on public.${p}_notifications to authenticated;
drop policy if exists "${p} notifications read" on public.${p}_notifications;
create policy "${p} notifications read" on public.${p}_notifications for select to authenticated
  using (to_user = auth.uid() or created_by = auth.uid()
         or (to_role = 'admin' and public.${p}_is_admin()) or to_role = 'customer');
-- Customers notify the admins (or themselves); admins notify anyone.
drop policy if exists "${p} notifications send" on public.${p}_notifications;
create policy "${p} notifications send" on public.${p}_notifications for insert to authenticated
  with check (created_by = auth.uid() and (to_role = 'admin' or to_user = auth.uid() or public.${p}_is_admin()));
drop policy if exists "${p} notifications mark read" on public.${p}_notifications;
create policy "${p} notifications mark read" on public.${p}_notifications for update to authenticated
  using (to_user = auth.uid() or (to_role = 'admin' and public.${p}_is_admin()));''';
  }

  /// SQL literal of a default value for a column, or null when there is none.
  String? defaultLiteral(DbColumn c) {
    final v = c.defaultValue?.trim();
    if (v == null || v.isEmpty) return null;
    switch (c.type) {
      case ColumnType.integer:
        final n = int.tryParse(v);
        return n?.toString();
      case ColumnType.decimal:
        final n = double.tryParse(v);
        return n?.toString();
      case ColumnType.boolean:
        return ['true', '1', 'yes', 'نعم'].contains(v.toLowerCase()) ? 'true' : 'false';
      case ColumnType.date:
        return v == 'now' || v == 'today' ? 'current_date' : (DateTime.tryParse(v) != null ? '${lit(v)}::date' : null);
      case ColumnType.datetime:
        return v == 'now' ? 'now()' : (DateTime.tryParse(v) != null ? '${lit(v)}::timestamptz' : null);
      case ColumnType.choice:
        return c.options.contains(v) ? lit(v) : (c.options.isNotEmpty ? lit(c.options.first) : null);
      default:
        return lit(v);
    }
  }

  String tableSql(DbTable t) {
    final full = table(t);
    final n = '${p}_${t.name}';
    final b = StringBuffer()
      ..writeln('-- ===== ${t.label} ($n): ${t.owner.label} =====')
      ..writeln('create table if not exists $full (')
      ..writeln('  id uuid primary key default gen_random_uuid(),')
      ..writeln('  created_at timestamptz not null default now(),')
      ..writeln('  updated_at timestamptz not null default now()')
      ..writeln(');');
    if (t.hasOwnerColumn) {
      b.writeln('alter table $full add column if not exists customer_id uuid default auth.uid() '
          'references auth.users(id) on delete cascade;');
      b.writeln('create index if not exists ${n}_customer_idx on $full (customer_id);');
    }
    for (final c in t.columns) {
      final def = defaultLiteral(c);
      b.writeln('alter table $full add column if not exists ${c.name} ${c.type.sql}${def == null ? '' : ' default $def'};');
      if (def != null) b.writeln('alter table $full alter column ${c.name} set default $def;');
      if (c.required) {
        // Existing rows without a value keep the table usable: then the column stays optional.
        b.writeln('do \$\$ begin alter table $full alter column ${c.name} set not null; '
            'exception when others then raise notice \'${c.name} has empty rows, kept optional\'; end \$\$;');
      } else {
        b.writeln('alter table $full alter column ${c.name} drop not null;');
      }
      b.writeln('alter table $full drop constraint if exists ${n}_${c.name}_check;');
      if (c.type == ColumnType.choice && c.options.isNotEmpty) {
        b.writeln('alter table $full add constraint ${n}_${c.name}_check check '
            '(${c.name} is null or ${c.name} in (${c.options.map(lit).join(', ')})) not valid;');
      }
      if (c.type == ColumnType.email) {
        b.writeln('alter table $full add constraint ${n}_${c.name}_check check '
            "(${c.name} is null or ${c.name} ~* '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+\$') not valid;");
      }
      if (c.unique) {
        b.writeln('create unique index if not exists ${n}_${c.name}_key on $full (${c.name});');
      }
    }
    b
      ..writeln('drop trigger if exists ${n}_touch on $full;')
      ..writeln('create trigger ${n}_touch before update on $full for each row execute function public.${p}_touch();')
      ..writeln(guardSql(t))
      ..writeln('alter table $full enable row level security;')
      ..writeln('grant select, insert, update, delete on $full to authenticated;')
      ..writeln(policiesSql(t));
    final notify = notifySql(t);
    if (notify.isNotEmpty) b.writeln(notify);
    return b.toString().trimRight();
  }

  /// Customers cannot set admin-only columns nor move a row to another customer.
  String guardSql(DbTable t) {
    final n = '${p}_${t.name}';
    final adminCols = t.columns.where((c) => c.adminOnly).toList();
    if (!t.hasOwnerColumn && adminCols.isEmpty) return 'drop trigger if exists ${n}_guard on ${table(t)};';
    final insertLines = <String>[
      if (t.hasOwnerColumn) '    new.customer_id := auth.uid();',
      for (final c in adminCols) '    new.${c.name} := ${defaultLiteral(c) ?? 'null'};',
    ];
    final updateLines = <String>[
      if (t.hasOwnerColumn) '    new.customer_id := old.customer_id;',
      for (final c in adminCols) '    new.${c.name} := old.${c.name};',
    ];
    return '''
create or replace function public.${n}_guard() returns trigger
language plpgsql security definer set search_path = public as \$\$
begin
  if auth.uid() is null or public.${p}_is_admin() then return new; end if;
  if tg_op = 'INSERT' then
${insertLines.join('\n')}
  else
${updateLines.join('\n')}
  end if;
  return new;
end \$\$;
drop trigger if exists ${n}_guard on ${table(t)};
create trigger ${n}_guard before insert or update on ${table(t)} for each row execute function public.${n}_guard();''';
  }

  String policiesSql(DbTable t) {
    final full = table(t);
    final n = '${p}_${t.name}';
    final admin = 'public.${p}_is_admin()';
    final own = '(customer_id = auth.uid() or $admin)';
    String pol(String name, String cmd, {String? using, String? check}) {
      return 'drop policy if exists "$n $name" on $full;\n'
          'create policy "$n $name" on $full for $cmd to authenticated'
          '${using == null ? '' : '\n  using ($using)'}${check == null ? '' : '\n  with check ($check)'};';
    }

    final drops = ['read', 'add', 'edit', 'remove', 'admin']
        .map((x) => 'drop policy if exists "$n $x" on $full;')
        .join('\n');
    final body = switch (t.owner) {
      TableOwner.catalog => [
          pol('read', 'select', using: 'true'),
          pol('admin', 'all', using: admin, check: admin),
        ],
      TableOwner.customer => [
          pol('read', 'select', using: own),
          pol('add', 'insert', check: own),
          pol('edit', 'update', using: own, check: own),
          pol('remove', 'delete', using: own),
        ],
      TableOwner.shared => [
          pol('read', 'select', using: 'true'),
          pol('add', 'insert', check: own),
          pol('edit', 'update', using: own, check: own),
          pol('remove', 'delete', using: own),
        ],
      TableOwner.admin => [
          pol('admin', 'all', using: admin, check: admin),
        ],
    };
    return '$drops\n${body.join('\n')}';
  }

  /// Text that describes a row in a notification: its title column and the admin-only columns (e.g. status).
  String summaryExpr(DbTable t) {
    final cols = <String>{
      if (t.titleColumn != null) t.titleColumn!.name,
      ...t.columns.where((c) => c.adminOnly).map((c) => c.name),
    };
    if (cols.isEmpty) return "''";
    return "concat_ws(' · ', ${cols.map((c) => 'new.$c::text').join(', ')})";
  }

  String notifySql(DbTable t) {
    final n = '${p}_${t.name}';
    final full = table(t);
    final ins = t.notifyOnInsert;
    final upd = t.notifyOnUpdate;
    if (ins == NotifyTarget.none && upd == NotifyTarget.none) {
      return 'drop trigger if exists ${n}_notify on $full;';
    }
    String send(NotifyTarget target, String title) {
      final data = "jsonb_build_object('table', ${lit(t.name)}, 'id', new.id)";
      switch (target) {
        case NotifyTarget.admin:
          return "insert into public.${p}_notifications (to_role, title, body, data, created_by) "
              "values ('admin', ${lit(title)}, ${summaryExpr(t)}, $data, auth.uid());";
        case NotifyTarget.customers:
          return "insert into public.${p}_notifications (to_role, title, body, data, created_by) "
              "values ('customer', ${lit(title)}, ${summaryExpr(t)}, $data, auth.uid());";
        case NotifyTarget.owner:
          if (!t.hasOwnerColumn) return 'null;';
          return "if new.customer_id is not null and new.customer_id is distinct from auth.uid() then "
              "insert into public.${p}_notifications (to_user, title, body, data, created_by) "
              "values (new.customer_id, ${lit(title)}, ${summaryExpr(t)}, $data, auth.uid()); end if;";
        case NotifyTarget.none:
          return 'null;';
      }
    }

    return '''
create or replace function public.${n}_notify() returns trigger
language plpgsql security definer set search_path = public as \$\$
begin
  if tg_op = 'INSERT' then
    ${send(ins, '${t.label}: جديد')}
  elsif tg_op = 'UPDATE' then
    ${send(upd, '${t.label}: تحديث')}
  end if;
  return new;
end \$\$;
drop trigger if exists ${n}_notify on $full;
create trigger ${n}_notify after insert or update on $full for each row execute function public.${n}_notify();''';
  }

  /// Row counts for the admin dashboard of the apps.
  String statsSql() {
    final parts = schema.tables
        .map((t) => "'${t.name}', (select count(*) from ${table(t)})")
        .followedBy(["'_customers', (select count(*) from public.${p}_profiles where role = 'customer')"])
        .join(', ');
    return '''
create or replace function public.${p}_stats() returns jsonb
language plpgsql stable security definer set search_path = public as \$\$
begin
  if not public.${p}_is_admin() then raise exception 'admins only'; end if;
  return jsonb_build_object($parts);
end \$\$;
grant execute on function public.${p}_stats() to authenticated;''';
  }

  String realtimeSql() {
    final names = [
      ...schema.tables.where((t) => t.realtime).map((t) => '${p}_${t.name}'),
      '${p}_notifications',
    ];
    final stmts = names
        .map((t) => "    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' "
            "and schemaname = 'public' and tablename = '$t') then "
            "execute 'alter publication supabase_realtime add table public.$t'; end if;")
        .join('\n');
    return '''
-- Live updates in the apps (Supabase Realtime).
do \$\$ begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
$stmts
  end if;
end \$\$;''';
  }

  /// Removes everything of this project (asked twice in Alpha before it runs).
  String dropSql() {
    final b = StringBuffer('-- Removes every table and function of project "$p".\n');
    for (final t in schema.tables) {
      b.writeln('drop table if exists ${table(t)} cascade;');
    }
    for (final x in ['notifications', 'device_tokens', 'push_config', 'profiles', 'admins']) {
      b.writeln('drop table if exists public.${p}_$x cascade;');
    }
    b.writeln('drop trigger if exists ${p}_on_auth_user_created on auth.users;');
    for (final f in ['is_admin()', 'role_for(text)', 'handle_new_user()', 'protect_role()', 'touch()', 'admin_added()',
      'register_device(text, text, text)', 'stats()', 'push_notify()']) {
      b.writeln('drop function if exists public.${p}_$f cascade;');
    }
    return b.toString();
  }
}
